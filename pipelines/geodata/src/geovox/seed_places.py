"""Extract halal-tagged OpenStreetMap places into SQL seed data.

OSM data is ODbL: if you load this seed into a public deployment, keep the
"© OpenStreetMap contributors" attribution and publish the places dataset
under ODbL (see docs/legal/data-licensing.md). Rows are marked
``source = 'osm'`` with their ``osm_id`` so they can be told apart.
"""

from __future__ import annotations

from pathlib import Path

import shapely
from pyproj import Transformer

from . import config, osm

CATEGORY = {
    "restaurant": "restaurant",
    "fast_food": "fast_food",
    "cafe": "cafe",
    "food_court": "fast_food",
    "bakery": "bakery",
    "pastry": "bakery",
    "confectionery": "bakery",
    "butcher": "butcher",
    "supermarket": "grocery",
    "convenience": "grocery",
    "greengrocer": "grocery",
    "deli": "grocery",
}


def _sql(v: str | None) -> str:
    if v is None or v == "":
        return "null"
    return "'" + v.replace("'", "''") + "'"


def extract(gpkg: Path, bbox: tuple[float, float, float, float]) -> list[dict]:
    to_wgs = Transformer.from_crs(2056, 4326, always_xy=True)
    out: list[dict] = []
    seen: set[str] = set()
    for layer in ("points", "multipolygons"):
        for f in osm.read_features(gpkg, layer, bbox):
            if f.get("diet:halal") not in ("yes", "only"):
                continue
            kind = f.get("amenity") or f.get("shop")
            if kind not in CATEGORY or not f.get("name"):
                continue
            osm_id = ("n" if layer == "points" else "") + str(f.get("osm_id"))
            if osm_id in seen:
                continue
            seen.add(osm_id)
            pt = f.geom if f.geom.geom_type == "Point" else shapely.point_on_surface(f.geom)
            lon, lat = to_wgs.transform(pt.x, pt.y)
            street = " ".join(x for x in (f.get("addr:street"), f.get("addr:housenumber")) if x)
            city = " ".join(x for x in (f.get("addr:postcode"), f.get("addr:city")) if x)
            out.append(
                {
                    "name": f.get("name"),
                    "category": CATEGORY[kind],
                    "cuisine": [c.strip().lower() for c in (f.get("cuisine") or "").split(";") if c.strip()][:6],
                    "lon": lon,
                    "lat": lat,
                    "address": ", ".join(x for x in (street, city) if x) or None,
                    "website": f.get("website") or f.get("contact:website"),
                    "phone": f.get("phone") or f.get("contact:phone"),
                    "opening_hours": f.get("opening_hours"),
                    "halal_level": "full" if f.get("diet:halal") == "only" else "partial",
                    "osm_id": osm_id,
                }
            )
    return sorted(out, key=lambda r: r["name"])


def write_seed(rows: list[dict], path: Path, timestamp: str) -> None:
    lines = [
        "-- Halal food places from OpenStreetMap (diet:halal=yes|only) around Lausanne.",
        f"-- Extract timestamp: {timestamp or 'unknown'}. Data (c) OpenStreetMap contributors, ODbL 1.0.",
        "-- Generated by: python -m geovox seed-places. Do not edit by hand.",
        "insert into public.places (name, category, cuisine, location, address, website, phone, opening_hours,",
        "  halal_level, certification, source, osm_id) values",
    ]
    values = []
    for r in rows:
        cuisine = "array[" + ", ".join(_sql(c) for c in r["cuisine"]) + "]::text[]" if r["cuisine"] else "'{}'::text[]"
        website = r["website"] if r["website"] and r["website"].startswith(("http://", "https://")) else None
        values.append(
            f"  ({_sql(r['name'])}, '{r['category']}', {cuisine}, "
            f"extensions.st_setsrid(extensions.st_makepoint({r['lon']:.7f}, {r['lat']:.7f}), 4326), "
            f"{_sql(r['address'])}, {_sql(website)}, {_sql(r['phone'])}, {_sql(r['opening_hours'])}, "
            f"'{r['halal_level']}', 'community', 'osm', {_sql(r['osm_id'])})"
        )
    lines.append(",\n".join(values))
    lines.append("on conflict (osm_id) do nothing;")
    path.write_text("\n".join(lines) + "\n")


def build_seed(out: Path, cache: Path, json_out: Path | None = None, area_name: str = config.SEED_AREA) -> int:
    """Halal places inside the area's context box: everything drawn in 3D.
    OSM ids are stable, so places already seeded keep their ids."""
    area = config.AREAS[area_name]
    gpkg, ts = osm.ensure_osm(area.coarse_bbox, cache)
    rows = extract(gpkg, area.coarse_bbox)
    write_seed(rows, out, ts)
    if json_out is not None:
        import json

        json_out.write_text(
            json.dumps({"source": "OpenStreetMap contributors (ODbL 1.0)", "timestamp": ts, "places": rows}, ensure_ascii=False, indent=1)
            + "\n"
        )
    return len(rows)
